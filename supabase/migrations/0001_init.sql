-- Free Pool Radar — core intelligence schema.
--
-- Design rules from the product spec:
--   * Observations and changes are append-only history. Never delete them.
--   * Every numeric claim carries its own evidence and verification level.
--   * A failed source must never mark an offer ENDED (§13).
--   * Token units are stored exactly as published; weighted tokens are not
--     silently converted to tokens (§56).

create extension if not exists "pgcrypto";

