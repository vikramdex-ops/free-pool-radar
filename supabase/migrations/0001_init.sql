-- ---------------------------------------------------------------------------
-- offers (§7.3)
-- ---------------------------------------------------------------------------

create table if not exists offers (
  id                        bigint generated by default as identity primary key,
  provider_id               bigint not null references providers (id) on delete cascade,
  model_id                  bigint references models (id) on delete set null,
  -- The provider's own model identifier, kept verbatim. This is the join key
  -- the sweep reconciles on, because a model may exist before it has a row in
  -- `models` (free credits, keyless routes, pools covering many models).
  model_id_text             text,
  -- Human label for the model when no models row is attached yet.
  model_label               text,
  offer_type                offer_type not null,
  status                    offer_status not null default 'unverified',

  access_requires_account  boolean not null default true,
  access_requires_subscription boolean not null default false,
  payment_required         boolean not null default false,
  card_required            boolean not null default false,
  api_key_required         boolean not null default true,
  keyless                  boolean not null default false,

  compatibility_openai    boolean not null default false,
  compatibility_anthropic boolean not null default false,
  compatibility_other     text,

  -- Quotas are published in the provider's own units (§55, §56).
  -- We never convert between dimensions without explicit documentation.
  rpm                      int,
  rpd                      int,
  tpm                      bigint,
  tpd                      bigint,
  monthly_limit            bigint,
  monthly_unit             text,
  token_limit              bigint,
  token_limit_unit         text,

  pool_size                bigint,
  pool_remaining           bigint,
  pool_unit                text,

  credit_amount            numeric,
  credit_currency          text,

  start_at                 timestamptz,
  end_at                   timestamptz,
  exhaustion_condition     text,

  commercial_use           text,
  data_policy              text,
  retention_policy         text,

  official_evidence_url    text,
  secondary_evidence_url   text,
  verification_level       verification_level not null default 'community',
  confidence               numeric,

  first_discovered_at      timestamptz not null default now(),
  first_verified_at        timestamptz,
  last_verified_at         timestamptz,
  last_seen_live_at        timestamptz,
  ended_at                 timestamptz,
  is_seed_data             boolean not null default false,
  -- sha256 of the normalised payload from the sweep that last wrote this row.
  -- Lets a retried sweep detect "nothing actually changed" without relying on
  -- wall-clock comparison alone (§78 idempotency).
  payload_hash             text,

  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
