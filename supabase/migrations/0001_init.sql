-- ---------------------------------------------------------------------------
-- updated_at maintenance
-- ---------------------------------------------------------------------------

create or replace function touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['providers','models','offers','events','sources']
  loop
    execute format(
      'drop trigger if exists trg_%1$s_touch on %1$I;', t);
    execute format(
      'create trigger trg_%1$s_touch before update on %1$I
         for each row execute function touch_updated_at();', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Freshness (§14) — computed in SQL so every surface agrees.
-- ---------------------------------------------------------------------------

create or replace view offer_freshness as
select
  o.id,
  case
    when o.last_verified_at is null                    then 'unverified'
    when now() - o.last_verified_at < interval '6 hours'   then 'fresh'
    when now() - o.last_verified_at < interval '24 hours'  then 'aging'
    when now() - o.last_verified_at < interval '72 hours'  then 'stale'
    else 'very_stale'
  end as freshness
from offers o;

comment on column offers.token_limit_unit is
  'Unit exactly as published: tokens | weighted_tokens | requests | credits | neurons. Never converted.';
comment on column offers.pool_unit is
  'Unit for pool_size/pool_remaining, kept verbatim from the provider.';
comment on table observations is
  'Append-only. One row per source per sweep; retained permanently.';
comment on table changes is
  'Append-only change log. dedupe_key makes a retried sweep idempotent.';
