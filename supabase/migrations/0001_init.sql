-- ---------------------------------------------------------------------------

create table if not exists observations (
  id               bigint generated by default as identity primary key,
  provider_id      bigint references providers (id) on delete cascade,
  offer_id         bigint references offers (id) on delete cascade,
  event_id         bigint references events (id) on delete cascade,
  source_id        bigint references sources (id) on delete set null,
  observed_at      timestamptz not null default now(),
  status           offer_status,
  raw_status       text,
  token_limit      bigint,
  pool_size        bigint,
  pool_remaining   bigint,
  rpm              int,
  rpd              int,
  tpm              bigint,
  tpd              bigint,
  model_count      int,
  source_url       text,
  source_type      text,
  -- sha256 of the normalised payload: makes re-running a sweep idempotent (§78).
  response_hash    text not null,
  raw_payload      jsonb,
  http_status      int,
  latency_ms       int,
  verification_level verification_level,
  created_at       timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- changes — the derived event log (§7.6, §15)
-- ---------------------------------------------------------------------------

create table if not exists changes (
  id           bigint generated by default as identity primary key,
  provider_id  bigint references providers (id) on delete cascade,
  offer_id     bigint references offers (id) on delete cascade,
  event_id     bigint references events (id) on delete cascade,
  change_type  change_type not null,
