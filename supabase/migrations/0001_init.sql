-- ---------------------------------------------------------------------------
-- providers (§7.1)
-- ---------------------------------------------------------------------------

create table if not exists providers (
  id                bigint generated by default as identity primary key,
  name              text not null,
  slug              text not null unique,
  official_url      text not null,
  logo_url          text,
  description       text,
  provider_type     text,
  country           text,
  status            provider_status not null default 'active',
  -- Denormalised rollups, refreshed by the change detector each sweep.
  free_model_count  int not null default 0,
  live_offer_count  int not null default 0,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  last_verified_at  timestamptz
);

-- ---------------------------------------------------------------------------
-- sources — the configurable source registry (§10).
-- Adding a provider must not require touching frontend code, so this
-- references providers by slug and is created after it.
-- ---------------------------------------------------------------------------

create table if not exists sources (
  id                bigint generated by default as identity primary key,
  provider_slug     text not null references providers (slug) on delete cascade,
  url               text not null,
  -- json | html | rsc | openapi
  source_type       text not null default 'json',
  priority          int  not null default 5,
  -- Key into the collector registry. Data-driven, never a component import.
  parser_key        text not null,
  enabled           boolean not null default true,
  is_official       boolean not null default true,
  interval_hours    numeric not null default 5,
  last_fetched_at   timestamptz,
  last_ok_at        timestamptz,
  last_status_code  int,
  last_latency_ms   int,
  last_error        text,
  health            source_health not null default 'live',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (provider_slug, url, parser_key)
);

